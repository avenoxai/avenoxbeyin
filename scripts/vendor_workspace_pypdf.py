#!/usr/bin/env python3
"""Reproduce the checksum-pinned parser transport from an already downloaded wheel.

No network, pip or Python environment setup. Preserve the upstream wheel intact,
including its BSD license. The transport uses an existing release allowlist path
so old updaters can load the new installer without a permissive bootstrap.
"""
import argparse
import base64
import hashlib
from pathlib import Path
import zipfile

NAME = 'pypdf-6.21.0-py3-none-any.whl'
SHA256 = '3aec619699dacb1b73f57e87d9adaa4424814517b2cc028de20adba5a37af4c4'
OCR_SHA256 = 'b3eb25619abfd7404835bf172104fae9e711f48088bd56d745d4e84d8a6a3f2a'
ROOT = Path(__file__).resolve().parents[1]


def generate(wheel):
    raw = Path(wheel).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('pypdf wheel checksum mismatch')
    with zipfile.ZipFile(wheel) as archive:
        license_text = archive.read('pypdf-6.21.0.dist-info/licenses/LICENSE').decode('utf-8')
        if any(name.endswith(('.so', '.pyd', '.dll', '.dylib')) for name in archive.namelist()):
            raise ValueError('native dependency is not approved')
    scan = (ROOT / 'tests/fixtures/v3/workspaces/runtime/ocr-scan-tr-en.pdf').read_bytes()
    scan_hash = hashlib.sha256(scan).hexdigest()
    if scan_hash != OCR_SHA256:
        raise ValueError('OCR probe checksum mismatch')
    scan_encoded = base64.b85encode(scan)
    scan_payload = '\n'.join('    ' + repr(scan_encoded[index:index + 100]) for index in range(0, len(scan_encoded), 100))
    encoded = base64.b85encode(raw)
    payload = '\n'.join('    ' + repr(encoded[index:index + 100]) for index in range(0, len(encoded), 100))
    return f'''# Generated by scripts/vendor_workspace_pypdf.py; do not edit payload by hand.
"""Installer-only pypdf transport; never imports third-party code into the core.

Upstream: https://pypi.org/project/pypdf/6.21.0/
Wheel: https://files.pythonhosted.org/ (exact PyPI wheel, pinned SHA256 below)
License: BSD-3-Clause, preserved inside the wheel and installed alongside it.
Existing updaters allow beyin_v3*.py payloads, but reject arbitrary ZIP assets.
This module is consumed by the installer and is not installed into the vault.
"""
import base64
import hashlib
import json

NAME = {NAME!r}
SHA256 = {SHA256!r}
LICENSE = {license_text!r}
PAYLOAD = (
{payload}
)
OCR_PROBE_SHA256 = {scan_hash!r}
OCR_PROBE = (
{scan_payload}
)


def managed_files():
    raw = base64.b85decode(PAYLOAD)
    if len(raw) != {len(raw)} or hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('pypdf bundled dependency integrity failed')
    lock = {{'schema': 1, 'name': 'pypdf', 'version': '6.21.0', 'filename': NAME,
            'sha256': SHA256, 'size': len(raw), 'license': 'BSD-3-Clause',
            'execution': 'isolated_reader_process', 'min_python': '3.11',
            'extras': [], 'docx': 'stdlib'}}
    scan = base64.b85decode(OCR_PROBE)
    if hashlib.sha256(scan).hexdigest() != OCR_PROBE_SHA256:
        raise ValueError('OCR probe integrity failed')
    root = '.claude/parser-assets/'
    return {{root + 'ocr-probe-tr-en.pdf': scan, root + NAME: raw, root + 'pypdf.lock.json':
            (json.dumps(lock, sort_keys=True, indent=2) + '\\n').encode('utf-8'),
            root + 'pypdf.LICENSE.txt': LICENSE.encode('utf-8')}}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('wheel', type=Path)
    args = parser.parse_args()
    target = ROOT / 'template/.claude/scripts/beyin_v3_parser_assets.py'
    target.write_text(generate(args.wheel), encoding='utf-8')
    print(target)
